#!/usr/bin/env python3
"""Write RESULTS.md from the accepted submissions (folders with a score.json).

Tracks are listed separately (models, systems, baselines). A submission marked publisher_entry is the
maintainer's own product: it is left out of the main tables and listed in its own section under the
same scoring, labelled "publisher's own system, self-run", until an outside reviewer has reproduced it.
usage: leaderboard.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TITLES = {"model": "Models", "system": "Products and pipelines", "baseline": "Baselines (no model, no paid service)"}


def row(meta, s):
    t = s["tasks"]
    ci = t["support"]["accuracy_95ci"]
    return (f"| {meta['system']} {meta['version']} | {meta['submitter']} | {meta['run_date']} | "
            f"{t['reference_exists']['accuracy']:.2f} | {t['quote']['accuracy']:.2f} | "
            f"{t['support']['accuracy']:.2f} ({ci[0]:.2f} to {ci[1]:.2f}) | {t['support']['macro_f1']:.2f} | "
            f"{t['support']['answer_rate']:.2f} |")


def main():
    subs = []
    for folder in sorted((ROOT / "submissions").iterdir()):
        if (folder / "score.json").exists():
            subs.append((json.load(open(folder / "submission.json")), json.load(open(folder / "score.json"))))
    head = ("| System | Submitted by | Run date | Reference exists, accuracy | Quote, accuracy | "
            "Support, accuracy (95% interval) | Support, macro-F1 | Support answered % |\n"
            "|---|---|---|---:|---:|---:|---:|---:|")
    lines = ["# Results", "", "Dataset: `seed-v0` (448 items, development split). Generated by "
             "`tools/leaderboard.py` from accepted submissions; do not edit by hand.", "",
             "Systems whose support intervals overlap should be read as tied.", ""]
    for track, title in TITLES.items():
        rows = [row(m, s) for m, s in subs if m["track"] == track and not m["publisher_entry"]]
        if rows:
            lines += [f"## {title}", "", head, *rows, ""]
    pub = [row(m, s) for m, s in subs if m["publisher_entry"]]
    lines += ["## Publisher's own system, self-run", "",
              "Entries from the maintainer's product are scored the same way and shown only here until an "
              "outside reviewer reproduces them. They are submitted through the same process (SUBMITTING.md)."]
    if pub:
        lines += ["", head, *pub]
    (ROOT / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print(f"RESULTS.md: {len(subs)} accepted submissions")


if __name__ == "__main__":
    main()
